#!/usr/bin/env node
// Regenerates packages/core/pricing.json (+ src/pricing-data.js) from LiteLLM's
// model_prices_and_context_window.json. Prices are written as USD per million tokens.
//
//   node scripts/sync-pricing.mjs                 # fetch from GitHub, PyPI wheel as fallback
//   node scripts/sync-pricing.mjs --from file.json  # use a local copy
//
// The downloaded JSON is treated strictly as data (JSON.parse only).
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CORE = join(ROOT, 'packages/core');
const URL_RAW = 'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';
const WHEEL_MEMBER = 'litellm/model_prices_and_context_window_backup.json';

const EXCLUDE = /(audio|realtime|tts|transcribe|image|embedding|search|deep-research|moderation|live|computer-use|customtools)/;
const FALLBACK_PREFS = {
  opus: ['claude-opus-4-5', 'claude-opus-4-1', 'claude-opus-4'],
  sonnet: ['claude-sonnet-4-5', 'claude-sonnet-4'],
  haiku: ['claude-haiku-4-5', 'claude-3-5-haiku'],
  gpt: ['gpt-5', 'gpt-5-codex'],
  gemini: ['gemini-2.5-pro', 'gemini-2.5-flash'],
};

async function fromGithub() {
  const res = await fetch(URL_RAW, { signal: AbortSignal.timeout(30000) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return { text: await res.text(), source: URL_RAW };
}

function fromPypi() {
  // Fresh empty scratch dir; the wheel is only unzipped for one JSON member, read as data.
  const dir = mkdtempSync(join(tmpdir(), 'pyrometer-litellm-'));
  try {
    execFileSync('pip', ['download', 'litellm', '--no-deps', '--only-binary=:all:', '-d', dir], { stdio: 'inherit' });
    const wheel = readdirSync(dir).find((f) => f.endsWith('.whl'));
    if (!wheel) throw new Error('no wheel downloaded');
    const text = execFileSync(
      'python3',
      ['-I', '-c', 'import sys,zipfile;sys.stdout.write(zipfile.ZipFile(sys.argv[1]).read(sys.argv[2]).decode())', join(dir, wheel), WHEEL_MEMBER],
      { maxBuffer: 64 * 1024 * 1024, cwd: tmpdir() },
    ).toString();
    return { text, source: `pypi:${wheel}#${WHEEL_MEMBER}` };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** @param {unknown} x */
const perM = (x) => (typeof x === 'number' && Number.isFinite(x) && x >= 0 ? Number((x * 1e6).toPrecision(10)) : null);

function select(raw) {
  const models = {};
  for (const [key, v] of Object.entries(raw)) {
    if (!v || typeof v !== 'object' || key === 'sample_spec') continue;
    const p = v.litellm_provider;
    let name = null;
    if (p === 'anthropic' && key.startsWith('claude-') && v.mode === 'chat') name = key;
    else if (p === 'openai' && (v.mode === 'chat' || v.mode === 'responses') && /^(gpt-4\.1|gpt-4o|gpt-5|o1|o3|o4|codex)/.test(key)) name = key;
    else if (p === 'gemini' && v.mode === 'chat' && key.startsWith('gemini/gemini-')) name = key.slice('gemini/'.length);
    if (!name || EXCLUDE.test(name)) continue;
    const input = perM(v.input_cost_per_token);
    const output = perM(v.output_cost_per_token);
    if (input === null || output === null) continue;
    models[name] = {
      input,
      output,
      cacheRead: perM(v.cache_read_input_token_cost),
      cacheWrite5m: perM(v.cache_creation_input_token_cost),
      cacheWrite1h: perM(v.cache_creation_input_token_cost_above_1hr),
    };
  }
  const sorted = Object.fromEntries(Object.keys(models).sort().map((k) => [k, models[k]]));
  const fallbacks = {};
  for (const [fam, prefs] of Object.entries(FALLBACK_PREFS)) {
    const hit = prefs.find((k) => sorted[k]);
    if (hit) fallbacks[fam] = hit;
  }
  return { models: sorted, fallbacks };
}

async function main() {
  const i = process.argv.indexOf('--from');
  let src;
  if (i > 0 && process.argv[i + 1]) {
    src = { text: readFileSync(process.argv[i + 1], 'utf8'), source: `file:${process.argv[i + 1].split('/').pop()}` };
  } else {
    try {
      src = await fromGithub();
    } catch (e) {
      console.error(`GitHub fetch failed (${e.message}); falling back to the litellm wheel on PyPI`);
      src = fromPypi();
    }
  }
  const raw = JSON.parse(src.text);
  const { models, fallbacks } = select(raw);
  const out = {
    source: src.source,
    syncedAt: new Date().toISOString().slice(0, 10),
    unit: 'USD per 1M tokens',
    fallbacks,
    models,
  };
  const json = JSON.stringify(out, null, 2) + '\n';
  writeFileSync(join(CORE, 'pricing.json'), json);
  writeFileSync(
    join(CORE, 'src/pricing-data.js'),
    `// GENERATED by scripts/sync-pricing.mjs from pricing.json. Do not edit.\n` +
      `/** @type {{ source: string, syncedAt: string, unit: string, fallbacks: Record<string, string>, models: Record<string, import('./pricing.js').ModelPrice> }} */\n` +
      `const PRICING_DATA = ${json.trimEnd()};\nexport default PRICING_DATA;\n`,
  );
  console.log(`wrote ${Object.keys(models).length} models from ${src.source}; fallbacks: ${JSON.stringify(fallbacks)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
